/**
 * Generates the SQL seed from the same geography the map draws (src/lib/map/layout.ts),
 * so the database and the parchment can never disagree.
 *
 *   npm run seed:gen          → supabase/seed.sql       (5 Banners, test season, 1 440 cells)
 *   npm run seed:gen -- demo  → supabase/seed_demo.sql  (optional fake armies, to see a living map)
 *   npm run seed:gen -- remap → supabase/apply_world_mask.sql (rewrites the ACTIVE season to the current mask)
 *
 * Apply with `supabase db reset` locally, or paste the file in the Supabase SQL editor.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { GRID_H, GRID_W } from "../config/game";
import { FACTIONS, FACTION_IDS } from "../src/lib/factions";
import { STATIC_CELLS, cellId } from "../src/lib/map/layout";
import { generateFakeWorld } from "../src/lib/map/fakeState";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const out = (name: string, sql: string) => {
  const p = join(process.cwd(), "supabase", name);
  writeFileSync(p, sql);
  console.log(`wrote ${p}`);
};

/** One character per cell: '.' land, '~' sea or river, '=' bridge, 'T' watchtower. */
function asciiMap(): string[] {
  const glyph = { normal: ".", blocked: "~", bridge: "=", bonus: "T" } as const;
  const rows: string[] = [];
  for (let y = 0; y < GRID_H; y++) {
    let r = "";
    for (let x = 0; x < GRID_W; x++) r += glyph[STATIC_CELLS[cellId(x, y)].kind];
    rows.push(r);
  }
  return rows;
}

function baseSeed() {
  const factions = FACTIONS.map((f) => `  (${q(f.id)}, ${q(f.name)}, ${q(f.color)}, ${f.base.x}, ${f.base.y})`).join(",\n");
  const rows = asciiMap()
    .map((r, y) => `    ${q(r)}${y < GRID_H - 1 ? "," : ""} -- ${String(y).padStart(2)}`)
    .join("\n");

  return `-- GENERATED by scripts/gen-seed.ts — do not edit by hand.
-- 5 Banners, one active test season starting on the latest Monday 17:00 UTC, its 1 440 cells.
begin;

insert into public.factions (id, name, color, base_x, base_y) values
${factions}
on conflict (id) do update set name = excluded.name, color = excluded.color,
  base_x = excluded.base_x, base_y = excluded.base_y;

-- Test season: latest Monday 17:00 UTC, lasts 14 days (SEASON_DAYS).
with start as (
  select case
    when date_trunc('week', now() at time zone 'utc') + interval '17 hours' <= now() at time zone 'utc'
      then date_trunc('week', now() at time zone 'utc') + interval '17 hours'
    else date_trunc('week', now() at time zone 'utc') + interval '17 hours' - interval '7 days'
  end as s
)
insert into public.seasons (number, name, starts_at, ends_at, status)
select 0, 'The Proving Grounds', s at time zone 'utc', (s + interval '14 days') at time zone 'utc', 'active'
from start
on conflict (number) do nothing;

-- The map, one character per cell: '.' land  '~' river  '=' bridge  'T' watchtower.
-- The 2×2 base camps (factions.base_x/base_y) are owned by their Banner from the first hour.
with map(rows) as (
  select array[
${rows}
  ]
),
grid as (
  select x, y, substr((select rows from map)[y + 1], x + 1, 1) as g
  from generate_series(0, ${GRID_W - 1}) x, generate_series(0, ${GRID_H - 1}) y
)
insert into public.cells (season_id, x, y, kind, base_faction_id, owner_faction_id)
select s.id, g.x, g.y,
  (case g.g when '~' then 'blocked' when '=' then 'bridge' when 'T' then 'bonus' else 'normal' end)::public.cell_kind,
  f.id, f.id
from grid g
cross join public.seasons s
left join public.factions f
  on g.x between f.base_x and f.base_x + 1 and g.y between f.base_y and f.base_y + 1
where s.number = 0
on conflict (season_id, x, y) do nothing;

commit;
`;
}

/** Fake armies (one demo wallet per Banner) so the real data path shows a living map. */
function demoSeed() {
  const world = generateFakeWorld(Date.now());
  const entries: string[] = [];
  for (const c of world.cells) {
    const sc = STATIC_CELLS[c.id];
    if (sc.kind === "blocked") continue;
    FACTION_IDS.forEach((f, i) => {
      const force = c.forces[f] ?? 0;
      if (force > 0) entries.push(`${sc.x},${sc.y},${i},${force}`);
    });
  }
  // wrap the packed list for readability
  const packed: string[] = [];
  for (let i = 0; i < entries.length; i += 12) packed.push(entries.slice(i, i + 12).join(";"));
  const ids = FACTION_IDS.map(q).join(", ");

  return `-- GENERATED by scripts/gen-seed.ts demo — fake armies for Season 0 only.
-- One demo wallet per Banner. Remove with:
--   delete from public.players where wallet like 'DEMO%';
--   update public.cells set owner_faction_id = base_faction_id, contested = false;
begin;

insert into public.players (wallet, faction_id, is_excluded)
select rpad('DEMO' || upper(f), 32, 'x'), f, false
from unnest(array[${ids}]) f
on conflict (wallet) do nothing;

-- packed "x,y,banner,force;" entries (banner index in the order above)
with raw as (
  select string_to_array(e, ',')::int[] as v
  from unnest(string_to_array(
${packed.map((p) => `    ${q(p)}`).join(" || ';' ||\n")}
  , ';')) e
),
d as (
  select v[1] as x, v[2] as y, (array[${ids}])[v[3] + 1] as faction, v[4] as force from raw
)
insert into public.deployments (wallet, cell_id, season_id, force)
select rpad('DEMO' || upper(d.faction), 32, 'x'), c.id, c.season_id, d.force
from d
join public.seasons s on s.number = 0
join public.cells c on c.season_id = s.id and c.x = d.x and c.y = d.y
on conflict (wallet, cell_id) do update set force = excluded.force;

-- Owner = strongest Banner (rule 5); base camps stay with their Banner.
-- Contested = top two within 10 %.
with s as (select id from public.seasons where number = 0),
ranked as (
  select cs.cell_id, cs.faction_id, cs.force,
    row_number() over (partition by cs.cell_id order by cs.force desc, cs.faction_id) as rk
  from public.cell_strength cs, s where cs.season_id = s.id
),
top as (
  select a.cell_id, a.faction_id as owner, a.force as f1, b.force as f2
  from ranked a left join ranked b on b.cell_id = a.cell_id and b.rk = 2
  where a.rk = 1
)
update public.cells c
set owner_faction_id = coalesce(c.base_faction_id, t.owner),
    contested = t.f2 is not null and (t.f1 - t.f2)::numeric / t.f1 < 0.10
from top t
where c.id = t.cell_id;

commit;
`;
}

/**
 * Rewrites the active season's cells to the current land/water mask, base camps and
 * watchtowers — without losing anyone's soldiers on land:
 *   1. soldiers standing on what becomes water, or on another Banner's new camp, go back to reserve;
 *   2. every cell gets its new kind and camp;
 *   3. every owner is recomputed (rule 5, camps stay with their Banner).
 */
function remapSql() {
  const rows = asciiMap()
    .map((r, y) => `    ${q(r)}${y < GRID_H - 1 ? "," : ""} -- ${String(y).padStart(2)}`)
    .join("\n");
  const bases = FACTIONS.map((f) => `  (${q(f.id)}, ${f.base.x}, ${f.base.y})`).join(",\n");
  return `-- GENERATED by scripts/gen-seed.ts remap — applies src/lib/map/mask.ts to the ACTIVE season.
begin;

update public.factions f set base_x = v.x, base_y = v.y
from (values
${bases}
) as v (id, x, y)
where f.id = v.id;

create temp table wg_target on commit drop as
with map(rows) as (
  select array[
${rows}
  ]
),
grid as (
  select x, y, substr((select rows from map)[y + 1], x + 1, 1) as g
  from generate_series(0, ${GRID_W - 1}) x, generate_series(0, ${GRID_H - 1}) y
)
select s.id as season_id, g.x, g.y,
  (case g.g when '~' then 'blocked' when '=' then 'bridge' when 'T' then 'bonus' else 'normal' end)::public.cell_kind as kind,
  case when g.g = '.' or g.g = 'T' then f.id end as base
from grid g
cross join public.seasons s
left join public.factions f
  on g.x between f.base_x and f.base_x + 1 and g.y between f.base_y and f.base_y + 1
where s.status = 'active';

-- 1. soldiers on new water, or on another Banner's new camp, go back to reserve
delete from public.deployments d
using public.cells c, wg_target t, public.players p
where d.cell_id = c.id and c.season_id = t.season_id and c.x = t.x and c.y = t.y and p.wallet = d.wallet
  and (t.kind = 'blocked' or (t.base is not null and p.faction_id is distinct from t.base));

update public.players p
set reserve = greatest(0, p.force - coalesce((select sum(d.force) from public.deployments d where d.wallet = p.wallet), 0));

-- 2. new kinds and camps (owners cleared first so the camp and water constraints hold)
update public.cells c set owner_faction_id = null, base_faction_id = null, contested = false
from wg_target t where c.season_id = t.season_id and c.x = t.x and c.y = t.y;
update public.cells c set kind = t.kind, base_faction_id = t.base, owner_faction_id = t.base
from wg_target t where c.season_id = t.season_id and c.x = t.x and c.y = t.y;

-- 3. every owner recomputed
select public.recompute_cell(c.id) from public.cells c join public.seasons s on s.id = c.season_id where s.status = 'active';

commit;
`;
}

if (process.argv.includes("demo")) out("seed_demo.sql", demoSeed());
else if (process.argv.includes("remap")) out("apply_world_mask.sql", remapSql());
else out("seed.sql", baseSeed());
